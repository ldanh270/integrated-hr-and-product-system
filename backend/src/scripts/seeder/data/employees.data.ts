export const generateEmployeeData = (index: number) => {
  const isTeamLeader = index < 3
  return {
    fullName: faker.person.fullName(),
    username: `${faker.internet.username().toLowerCase()}${index}`,
    email: `employee-${index + 1}@hr.local`,
    role: isTeamLeader ? ("team_leader" as const) : ("employee" as const),
    status: "active" as const,
    employeeType: "full_time" as const,
    phone: `091${faker.string.numeric(7)}`,
    dateOfBirth: faker.date.birthdate({ min: 22, max: 55, mode: "age" }),
    nationalId: `030${faker.string.numeric(9)}`,
    address: faker.location.streetAddress(true),
    avatar: {
      url: faker.image.avatar(),
      id: `avatar_${index}`,
    },
    position: isTeamLeader ? "Team Leader" : faker.person.jobTitle(),
    startDate: faker.date.past({ years: 2 }),
    endDate: null,
    failedLoginCount: 0,
    lockedUntil: null,
    lastLoginAt: faker.date.recent({ days: 30 }),
  }
}
